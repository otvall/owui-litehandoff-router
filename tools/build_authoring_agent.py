"""Build the standalone authoring Tool and importable Skill without downloads."""

import argparse
import ast
import io
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/lite_handoff_router"
SKILL = ROOT / "docs/skills/routing-skill-authoring"


def authoring_archive(files):
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, content in sorted(files.items()):
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, content)
    return buffer.getvalue()


def build(destination=None):
    destination = Path(destination or ROOT / "dist")
    destination.mkdir(parents=True, exist_ok=True)
    template = (ROOT / "docs/templates/routing-skill/SKILL.md").read_text(encoding="utf-8")
    renderer = (SOURCE / "routing_skill_renderer.py").read_text(encoding="utf-8")
    parts = []
    for module in ("routing_skill_renderer", "authoring"):
        tree = ast.parse((SOURCE / (module + ".py")).read_text(encoding="utf-8"))
        tree.body = [node for node in tree.body if not (
            isinstance(node, ast.ImportFrom) and node.level
            or isinstance(node, ast.If) and ast.unparse(node.test) == "__name__ == '__main__'"
        )]
        for node in tree.body:
            if isinstance(node, ast.FunctionDef) and node.name == "authoring_template":
                node.body = [ast.Return(value=ast.Constant(value=template))]
        parts.append(ast.unparse(ast.fix_missing_locations(tree)))
    tool = '''"""
title: Routing Skill Authoring
description: Inspect writable Workspace Models and create routing Skills without execute_code.
version: 0.1.0
developed_for_open_webui_version: 0.13.3
"""
# Generated by tools/build_authoring_agent.py. Edit src/, then rebuild.
''' + "\n\n".join(parts) + "\n"
    compile(tool, "routing_skill_authoring.py", "exec")
    (destination / "routing_skill_authoring.py").write_text(tool, encoding="utf-8")
    # The portable helper and template are generated copies of their canonical sources.
    files = {str(path.relative_to(SKILL)): path.read_bytes()
             for path in SKILL.rglob("*") if path.is_file() and "__pycache__" not in path.parts}
    files["scripts/render_routing_skill.py"] = renderer.encode()
    files["references/routing-skill-template.md"] = template.encode()
    skill_zip = authoring_archive({"routing-skill-authoring/" + name: content for name, content in files.items()})
    (destination / "routing-skill-authoring.zip").write_bytes(skill_zip)
    bundle = {
        "routing_skill_authoring.py": tool.encode(),
        "routing-skill-authoring.zip": skill_zip,
        "system-prompt.md": (ROOT / "docs/templates/routing-author-system-prompt.md").read_bytes(),
        "SETUP.md": (ROOT / "docs/routing-author-agent.md").read_bytes(),
    }
    (destination / "routing-skill-authoring-agent.zip").write_bytes(authoring_archive(bundle))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--destination", type=Path)
    build(parser.parse_args().destination)
