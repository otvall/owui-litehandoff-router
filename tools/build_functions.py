"""Deterministically inline each entrypoint's local dependencies for OWUI upload."""

import ast
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'src/lite_handoff_router'
ENTRIES = {
    'router_preparation': 'Router Preparation',
    'lite_handoff_router': 'Lite Handoff Router',
}


def build(destination=None, owui_version="0.12.3"):
    if owui_version not in {"0.11.1", "0.12.3"}:
        raise ValueError("Unsupported OWUI build target: " + str(owui_version))
    default = ROOT / 'dist'
    if owui_version == "0.11.1":
        default /= 'owui-0.11.1'
    destination = Path(destination or default)
    destination.mkdir(parents=True, exist_ok=True)
    for entry, title in ENTRIES.items():
        parts, visited = [], set()

        def inline(module):
            if module in visited:
                return
            visited.add(module)
            tree = ast.parse((SOURCE / (module.replace('.', '/') + '.py')).read_text())
            if module == 'profiles':
                for node in tree.body:
                    if isinstance(node, ast.Assign) and any(
                            isinstance(target, ast.Name) and target.id == 'ROUTER_TARGET_VERSION'
                            for target in node.targets):
                        node.value = ast.Constant(owui_version)
            prefix = module.split('.')[:-1]
            for node in tree.body:
                if isinstance(node, ast.ImportFrom) and node.level:
                    parent = prefix[:len(prefix) - node.level + 1]
                    inline('.'.join(parent + node.module.split('.')))
            tree.body = [node for node in tree.body if not (
                isinstance(node, ast.ImportFrom) and (node.level or node.module == '__future__')
            )]
            parts.append('# Source: ' + module + '\n' + ast.unparse(tree))

        inline('entrypoints.' + entry)
        display_title = title if owui_version == "0.12.3" else title + " (OWUI " + owui_version + ")"
        header = f'''"""
title: {display_title}
version: 0.1.0
required_open_webui_version: {owui_version}
"""
from __future__ import annotations
# Generated by tools/build_functions.py. Edit src/, then rebuild.
'''
        text = header + '\n\n'.join(parts) + '\n'
        ast.parse(text)
        (destination / (entry + '.py')).write_text(text)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--owui-version', choices=('0.11.1', '0.12.3'), default='0.12.3')
    parser.add_argument('--destination', type=Path)
    args = parser.parse_args()
    build(args.destination, args.owui_version)
